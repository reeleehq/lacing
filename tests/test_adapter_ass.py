# --- load: a real-world script ----------------------------------------------


class TestLoadAegisub:
    @pytest.fixture
    def store(self):
        return adapter_module.load(AEGISUB_ASS)

    def test_dialogues_are_lines_with_plain_text(self, store):
        assert _spans(store) == [
            ("Hello, world, again\nline two", _s(100), _s(350)),
            ("A sign, top", _s(200), _s(400)),
            ("Karaoke", _s(700), _s(900)),
            ("late line", _s(372345), _s(372400)),
        ]

    def test_body_keeps_every_field_and_the_raw_text(self, store):
        first, sign, *_ = _tier(store, "lines")
        assert first.body == {
            "text": "Hello, world, again\nline two",
            "raw": "Hello, {\\i1}world{\\i0}, again\\Nline\\htwo",
            "style": "Default",
            "fields": {
                "Layer": "0",
                "Name": "Alice",
                "MarginL": "0",
                "MarginR": "0",
                "MarginV": "0",
                "Effect": "",
            },
            "index": 0,
        }
        assert first.body_schema_uri == EVENT
        assert sign.body["style"] == "Sign"
        assert sign.body["fields"]["MarginV"] == "0050"  # verbatim
        assert sign.body["raw"] == "{\\an8\\pos(960,50)}A sign, top"

    def test_one_lines_tier_for_every_style(self, store):
        assert store.get_tier("lines").stereotype == TierStereotype.NONE
        assert {a.body["style"] for a in _tier(store, "lines")} == {"Default", "Sign"}

    def test_comments_are_kept_on_their_own_tier(self, store):
        (note,) = _tier(store, "comments")
        assert note.body["text"] == "not shown, a note"
        assert note.body["index"] == 2
        # a comment's karaoke tags are not read as syllables
        assert all(w.body["event"] != 2 for w in _tier(store, "words"))

    def test_script_metadata_is_one_annotation(self, store):
        (script,) = _tier(store, "script")
        assert script.body_schema_uri == SCRIPT
        assert script.interval == TimeInterval(
            RationalTime(0, 1000), RationalTime(0, 1000)
        )
        sections = script.body["sections"]
        assert [s["name"] for s in sections] == [
            "Script Info",
            "Aegisub Project Garbage",
            "V4+ Styles",
            "Fonts",
        ]
        assert "Title: Demo, with a comma" in sections[0]["lines"]
        assert len(sections[2]["lines"]) == 3
        # the bracketed uuencoded line is font data, not a section header
        assert sections[3]["lines"][1].startswith("[!!!")
        assert script.body["events"] == {
            "name": "Events",
            "position": 4,
            "format": EVENTS_FORMAT.removeprefix("Format: ").split(", "),
            "lines": [],
        }

    def test_bom_and_crlf(self):
        crlf = AEGISUB_ASS.replace("\n", "\r\n").encode("utf-8")
        assert _view(adapter_module.load(crlf)) == _view(
            adapter_module.load(AEGISUB_ASS)
        )

    def test_path_source(self, tmp_path):
        path = tmp_path / "demo.ssa"
        path.write_text(AEGISUB_ASS, encoding="utf-8")
        assert len(_tier(adapter_module.load(path), "lines")) == 4
        assert len(_tier(adapter_module.load(str(path)), "lines")) == 4

    def test_text_keeps_its_trailing_blanks(self):
        src = f"[Events]\n{EVENTS_FORMAT}\nDialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,a  \n"
        (line,) = _tier(adapter_module.load(src), "lines")
        assert line.body["raw"] == "a  "

    def test_an_ssa_v4_script(self):
        src = (
            "[Script Info]\nScriptType: v4.00\n\n[V4 Styles]\n"
            "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, "
            "TertiaryColour, BackColour, Bold, Italic, BorderStyle, Outline, "
            "Shadow, Alignment, MarginL, MarginR, MarginV, AlphaLevel, Encoding\n"
            "Style: Default,Arial,20,16777215,65535,65535,0,0,0,1,2,2,2,10,10,10,0,0\n\n"
            "[Events]\n"
            "Format: Marked, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n"
            "Dialogue: Marked=0,0:00:01.00,0:00:02.00,Default,,0000,0000,0000,,old, school\n"
        )
        store = adapter_module.load(src)
        (line,) = _tier(store, "lines")
        assert line.body["fields"]["Marked"] == "Marked=0"
        assert line.body["text"] == "old, school"
        assert _view(adapter_module.load(adapter_module.dump(store))) == _view(store)

    def test_no_format_line_uses_the_default(self):
        src = "[Events]\nDialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,hi, there\n"
        store = adapter_module.load(src)
        assert _spans(store) == [("hi, there", _s(100), _s(200))]
        assert EVENTS_FORMAT in adapter_module.dump(store).decode()

    def test_other_event_lines_are_kept(self):
        src = (
            f"[Events]\n{EVENTS_FORMAT}\n; a comment line\n"
            "Sound: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,ding.wav\n"
            "Dialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,hi\n"
        )
        store = adapter_module.load(src)
        (script,) = _tier(store, "script")
        assert script.body["events"]["lines"] == [
            "; a comment line",
            "Sound: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,ding.wav",
        ]
        back = adapter_module.load(adapter_module.dump(store))
        (script_back,) = _tier(back, "script")
        # the dump adds the [Script Info] and styles sections ASS requires
        for key in ("format", "lines"):
            assert script_back.body["events"][key] == script.body["events"][key]
        assert _spans(back) == _spans(store)


