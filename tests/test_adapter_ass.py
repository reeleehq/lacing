class TestKaraoke:
    def test_syllables_follow_one_another_from_the_event_start(self):
        store = adapter_module.load(AEGISUB_ASS)
        assert _spans(store, "words") == [
            ("Ka", _s(700), _s(750)),
            ("ra", _s(750), _s(790)),
            ("o", _s(790), _s(850)),
            ("ke", _s(850), _s(900)),
        ]
        assert [w.body["karaoke"] for w in _tier(store, "words")] == [
            "k",
            "kf",
            "ko",
            "K",
        ]
        assert {w.body["event"] for w in _tier(store, "words")} == {3}
        assert {w.body_schema_uri for w in _tier(store, "words")} == {SYLLABLE}

    def test_words_tier_is_included_in_lines(self):
        store = adapter_module.load(AEGISUB_ASS)
        words = store.get_tier("words")
        assert words.stereotype == TierStereotype.INCLUDED_IN
        assert words.parent == "lines"
        assert _included_in_violations(store) == []

    def test_gaps_other_tags_and_decimal_durations(self):
        store = adapter_module.load(KARAOKE_ASS)
        # {\k50} is a lead-in pause; {\K12.5} is 125 ms, exactly
        assert _spans(store, "words") == [
            ("so", _s(1050), _s(1075)),
            ("long", _s(1075), _s(1105)),
            ("and", _s(1105), _s(1150)),
            ("bye", _s(1150), Fraction(11625, 1000)),
        ]
        (line,) = _tier(store, "lines")
        assert line.body["text"] == "so long and bye"

    def test_kt_moves_the_next_syllable(self):
        src = f"[Events]\n{EVENTS_FORMAT}\nDialogue: 0,0:00:01.00,0:00:05.00,Default,,0,0,0,,{{\\k20}}a{{\\kt100\\k30}}b\n"
        assert _spans(adapter_module.load(src), "words") == [
            ("a", _s(100), _s(120)),
            ("b", _s(200), _s(230)),
        ]

    def test_syllables_past_the_event_end_are_cut_there(self):
        src = f"[Events]\n{EVENTS_FORMAT}\nDialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,{{\\k80}}a{{\\k80}}b{{\\k80}}c\n"
        store = adapter_module.load(src)
        assert _spans(store, "words") == [
            ("a", _s(100), _s(180)),
            ("b", _s(180), _s(200)),
            ("c", _s(200), _s(200)),
        ]
        assert _included_in_violations(store) == []
        # the raw text still has the tags, and dumps back unchanged
        assert _events(adapter_module.dump(store))[0].endswith(
            "{\\k80}a{\\k80}b{\\k80}c"
        )

    def test_layered_copies_keep_their_own_syllables(self):
        # karaoke FX scripts stack the same line on several layers
        row = "0:00:01.00,0:00:02.00,Default,,0,0,0,,{\\k50}a{\\k50}b"
        src = f"[Events]\n{EVENTS_FORMAT}\nDialogue: 0,{row}\nDialogue: 1,{row}\n"
        store = adapter_module.load(src)
        blob = adapter_module.dump(store)
        assert _events(blob) == [f"Dialogue: 0,{row}", f"Dialogue: 1,{row}"]

    def test_no_karaoke_no_words_tier(self):
        src = f"[Events]\n{EVENTS_FORMAT}\nDialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,plain\n"
        store = adapter_module.load(src)
        assert store.get_tier("words") is None
        assert store.get_tier("comments") is None


# --- exact times ------------------------------------------------------------


class TestTimes:
    def test_centiseconds_are_exact_at_any_rate_that_holds_them(self):
        for rate in (100, 1000, 48000):
            (line,) = _tier(
                adapter_module.load(
                    f"[Events]\nDialogue: 0,0:00:01.01,12:00:00.99,Default,,0,0,0,,x\n",
                    rate=rate,
                ),
                "lines",
            )
            assert line.interval.start.rate == rate
            assert line.interval.start.to_fraction() == Fraction(101, 100)
            assert line.interval.end.to_fraction() == 12 * 3600 + Fraction(99, 100)

    def test_a_rate_that_cannot_hold_a_centisecond_raises(self):
        with pytest.raises(LossyTimeConversionError):
            adapter_module.load(
                "[Events]\nDialogue: 0,0:00:01.01,0:00:02.00,Default,,0,0,0,,x\n",
                rate=24,
            )

    def test_a_decimal_karaoke_duration_finer_than_the_rate_raises(self):
        src = "[Events]\nDialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,{\\k1.25}x\n"
        with pytest.raises(LossyTimeConversionError):
            adapter_module.load(src, rate=1000)
        (w,) = _tier(adapter_module.load(src, rate=10000), "words")
        assert w.interval.end.to_fraction() == Fraction(10125, 10000)

    def test_dump_truncates_to_the_centisecond_monotonically(self):
        s = MemoryStore()
        s.add(_ann(1009, 1011, "a b"))  # 1.009 .. 1.011 s
        s.add(_ann(1009, 1010, "a", tier="words"))
        s.add(_ann(1010, 1011, "b", tier="words"))
        blob = adapter_module.dump(s)
        assert _events(blob) == [
            "Dialogue: 0,0:00:01.00,0:00:01.01,Default,,0,0,0,,{\\k1}a {\\k0}b"
        ]
        back = adapter_module.load(blob)
        assert _spans(back, "words") == [
            ("a", _s(100), _s(101)),
            ("b", _s(101), _s(101)),
        ]

    def test_hours_past_nine(self):
        s = MemoryStore()
        s.add(_ann(36_000_000, 36_001_000, "late"))
        assert _events(adapter_module.dump(s)) == [
            "Dialogue: 0,10:00:00.00,10:00:01.00,Default,,0,0,0,,late"
        ]

    def test_a_negative_time_cannot_be_written(self):
        s = MemoryStore()
        s.add(
            _ann(0, 1000, "x").model_copy(
                update={
                    "reference": MediaRef(
                        asset_id="a",
                        interval=TimeInterval(
                            RationalTime(-1, 1000), RationalTime(1000, 1000)
                        ),
                    )
                }
            )
        )
        with pytest.raises(ValueError, match="negative"):
            adapter_module.dump(s)


