class TestMalformed:
    @pytest.mark.parametrize(
        "event, message",
        [
            (
                "Dialogue: 0,0:0a:01.00,0:00:02.00,Default,,0,0,0,,x",
                "malformed ASS time",
            ),
            (
                "Dialogue: 0,0:00:01.000,0:00:02.00,Default,,0,0,0,,x",
                "malformed ASS time",
            ),
            ("Dialogue: 0,0:00:01.00,0:00:02.00,Default", "4 fields"),
            ("Dialogue: 0,0:00:03.00,0:00:02.00,Default,,0,0,0,,x", "ends before"),
            ("just some text", "malformed \\[Events\\] line"),
            ("Dialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,{\\kx}a", "karaoke"),
            ("Dialogue: 0,0:00:01.00,0:00:02.00,Default,,0,0,0,,{\\k-5}a", "karaoke"),
            (EVENTS_FORMAT, "second or late Format"),
        ],
    )
    def test_raises_with_the_line_number(self, event, message):
        src = (
            f"[Script Info]\nScriptType: v4.00+\n\n[Events]\n{EVENTS_FORMAT}\n{event}\n"
        )
        with pytest.raises(ValueError, match=message) as info:
            adapter_module.load(src)
        assert "line 6" in str(info.value)

    def test_a_format_without_text_last(self):
        with pytest.raises(ValueError, match="line 2: .*Text"):
            adapter_module.load("[Events]\nFormat: Start, End, Text, Style\n")

    @pytest.mark.parametrize(
        "source",
        [
            "",
            "1\n00:00:01,000 --> 00:00:02,000\nhello\n",  # SubRip
            "[Script Info]\nTitle: no events\n",
            b"\xef\xbb\xbfjust text\n",
        ],
    )
    def test_input_with_no_events_section_is_not_ass(self, source):
        with pytest.raises(ValueError, match="not an ASS/SSA file"):
            adapter_module.load(source)


