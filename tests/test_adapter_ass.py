def _tier(store, name):
    return sorted(
        (a for a in store.all() if a.tier == name),
        key=lambda a: (a.interval.start.to_fraction(), a.interval.end.to_fraction()),
    )


def _spans(store, tier="lines"):
    """``(text, start, end)`` per annotation of ``tier``, times as Fractions."""
    return [
        (a.body["text"], a.interval.start.to_fraction(), a.interval.end.to_fraction())
        for a in _tier(store, tier)
    ]


def _view(store):
    """Comparable view of a store: everything but ids and provenance."""
    return sorted(
        (a.tier, a.interval.start, a.interval.end, a.body_schema_uri, repr(a.body))
        for a in store.all()
    )


def _included_in_violations(store, parent="lines", child="words"):
    return validate_tier_constraint(
        store.get_tier(parent),
        store.get_tier(child),
        [a.interval for a in _tier(store, parent)],
        [a.interval for a in _tier(store, child)],
    )


def _ann(start_ms, end_ms, text, *, tier="lines", body=None, uri=None, rate=1000):
    return Annotation(
        id=uuid4(),
        tier=tier,
        reference=MediaRef(
            asset_id="ass:sample",
            interval=TimeInterval(
                RationalTime(start_ms, rate), RationalTime(end_ms, rate)
            ),
        ),
        body=body if body is not None else {"text": text},
        body_schema_uri=uri or "annot://schema/lyric-line/v1",
        provenance=Provenance(
            was_generated_by="user:test",
            was_attributed_to="test",
            generated_at_time=RationalTime.zero(1000),
        ),
    )


def _events(blob: bytes) -> list[str]:
    return [
        line
        for line in blob.decode().splitlines()
        if line.startswith(("Dialogue:", "Comment:"))
    ]


def _s(cs: int) -> Fraction:
    return Fraction(cs, 100)


